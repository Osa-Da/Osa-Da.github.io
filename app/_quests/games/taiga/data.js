/* =========================================================================
   ДАННЫЕ ИГРЫ «ТАЙГА: КРУШЕНИЕ».

   Вся логика отрисовки — в assets/engine.js. Здесь только сюжет, персонажи,
   задания, инвентарь, коды и ПРАВИЛА (в комментариях и глоссарии).

   =========================================================================
   МЕХАНИКИ ИГРЫ — ПОЛНОЕ ОПИСАНИЕ
   =========================================================================

   === ЛОКАЦИИ (всего три) ===

   ДОМ (убежище) — тепло, безопасно. Здесь ночуют, голосуют, конфликтуют.
   САМОЛЁТ (обломки) — багажный отсек (заперт), вещи, еда, документы,
                       детали рации, улики. Нос и хвост разнесены.
   УЛИЦА — между домом и самолётом. Лес, река, хворост.
           Ночью, в метель, при медведях — смертельно.

   === ДЕНЬ И НОЧЬ ===

   ДЕНЬ — все ходят по локациям. Собирают ресурсы, ищут детали рации,
          торгуют, разговаривают. Конфликтов и голосований НЕТ.

   СУМЕРКИ — ведущий объявляет: «Сумерки. Через 5 минут — ночь».
             Кто не успел вернуться в дом — становится ОСЛАБЛЕННЫМ до утра.

   НОЧЬ — все в доме. Улица автоматически смертельна (метель, холод, медведи).
          Ночью происходят: голосования, конфликты, кражи, разговоры шёпотом, сон.
          Ночь длится, пока все не закончат дела. Потом ведущий объявляет рассвет.

   РАССВЕТ — новый день. Все просыпаются. Ослабление спадает.

   === СТАТУСЫ ===

   СЫТ — может всё: конфликты, голосования, действия.

   ГОЛОДЕН — не может в конфликт. Если голоден 2 цикла подряд — умирает.

   ОСЛАБЛЕН — после конфликта (на любой стороне) или если не успел в дом.
              Не может голосовать. Не может участвовать в конфликтах.
              Может только разговаривать и спать. Спадает утром.

   ИЗОЛИРОВАН — белые очки. Не влияет на игру. Общается только с другими
                изолированными (не по игре). Через 1 цикл возвращается.
                Если у изолируемого нет еды — один из тех, кто его изолировал,
                обязан отдать ему 1 еду. Если еды нет ни у кого — изоляция
                происходит без еды. Мы же не варвары.

   МЁРТВ — чёрные очки. Наблюдает. Общается только с другими мёртвыми.

   === КОНФЛИКТЫ ===

   Конфликт — когда две стороны делят одну ситуацию.
   Одна сторона — «орёл», другая — «решка».

   Формула:
   1. Нападающие объявляют действие (убить, отобрать, изолировать).
   2. Защищающийся выбирает сторону (орёл или решка).
   3. Монетка подкидывается за каждого нападающего.
   4. Выпала сторона нападающих — цель погибает (или теряет предмет, или изолируется).
   5. Выпала сторона защищающихся — монетка за следующего нападающего.
   6. Если ВСЕ нападающие выкинули сторону защищающихся — цель выжила.
   7. Все участники конфликта становятся ОСЛАБЛЕННЫМИ.

   Шанс выжить: (1/2)^n, где n — число нападающих.
   Нападающих | Шанс выжить
   1          | 50%
   2          | 25%
   3          | 12.5%
   4          | 6.25%
   5          | 3.125%

   Если у защищающегося есть союзники — каждый союзник «поглощает»
   одного нападающего.

   === ИНИЦИАЦИЯ ДЕЙСТВИЯ ===

   Чтобы НАЧАТЬ действие (убить, отобрать, изолировать), нужно преимущество.

   Действие    | Преимущество | Пример (12 живых)
   Убить       | +4           | 8 нападающих против 4 защищающихся
   Изолировать | +3           | 7 нападающих против 4 защищающихся
   Отобрать    | +2           | 6 нападающих против 4 защищающихся

   Формула зависит от количества живых:

   Живых | Убить | Изолировать | Отобрать
   6     | +3    | +2          | +1
   8     | +3    | +2          | +2
   10    | +4    | +3          | +2
   12    | +4    | +3          | +2
   14    | +5    | +4          | +3
   16    | +6    | +4          | +3

   Если преимущество не набрано — действие не начинается.
   Если цель НЕ против — действие происходит без конфликта.
   Если цель против — начинается конфликт (монетки).

   === ГОЛОСОВАНИЯ ===

   Объявляются ночью. Каждый игрок — 1 раз за ночь.
   Пилот — 2 раза за ночь. Богач — не может вообще (но может купить трибуну).
   Голосовать могут все, кто не ослаблен. Сколько угодно раз.

   Типы:
   Изолировать — порог 1/3 живых + 1
   Убить — порог 1/2 живых + 1
   Отобрать — порог 1/4 живых + 1

   Пороги:
   Живых | Изолировать | Убить | Отобрать
   6     | 3           | 4     | 2
   8     | 3           | 5     | 3
   10    | 4           | 6     | 3
   12    | 5           | 7     | 4
   14    | 5           | 8     | 4
   16    | 6           | 9     | 5

   Если порог не набран — голосование провалено. Объявивший теряет попытку.
   Если набран — действие происходит. Цель может быть против — тогда конфликт.

   === СОБЫТИЯ ===

   РАССВЕТ — новый день. Все просыпаются.
   СУМЕРКИ — 5 минут до ночи. Кто не в доме — ослаблен.
   НОЧЬ — все в доме. Голосования, конфликты, кражи.
   МЕТЕЛЬ — все, кто не в доме — ослаблены.
   МЕДВЕДИ — все, кто не в доме — погибают.
             Кроме местных — они становятся ослабленными до конца игры.
   РАЦИЯ_ГОТОВА — сигнал уйдёт с рассветом. Нужно пережить ещё 1 сутки.
   ПОМОЩЬ_ПРИБЫЛА — спасение. Преступники — в тюрьму.
   ПОБЕГ — Выживальщик уходит. Кто с ним?

   === КОНЦОВКИ ===

   1. СПАСЕНИЕ — рация собрана, пережили 1 сутки. Законопослушные свободны,
                 преступники в тюрьму.
   2. ПОБЕГ — Выживальщик уходит. Кто с ним — выживают, если припасов хватает.
   3. СМЕРТЬ ВСЕХ — Сатанист открывает дверь во время метели или медведей.
   4. ДВА ХИЩНИКА — Сатанист и Главарь договариваются. Один предаёт другого.
   5. САМОСУД — Маршал разоблачает Сатаниста. Группа убивает его.

   === РАЗНИЦА МЕЖДУ СОЛО И ГРАЖДАНСКИМИ ===

   СОЛО — личная уникальная цель, часто конфликтует с группой.
          Двигают сюжет. Всегда есть в игре.
   ГРАЖДАНСКИЕ — просто выжить. Наполняют игру.
                 Добавляются/убираются по количеству игроков.

   ========================================================================= */

